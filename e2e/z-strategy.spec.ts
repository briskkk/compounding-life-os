import { test, expect } from '@playwright/test'

test('结构页直接分组，并按自定义组合设目标与查看分类复盘', async ({ page }) => {
  await page.goto('/review/groups')
  await expect(page.getByRole('heading', { name: '大类 · 股票' })).toBeVisible()
  await page.goto('/positions?view=composition')
  const manager = page.getByRole('region', { name: '资产分组管理' })
  await expect(manager).toBeVisible()
  await expect(manager).toContainText('当前持仓')
  const asset = manager.locator('[data-asset-id]').filter({ hasText: '600519' })
  const second = manager.locator('[data-asset-id]').filter({ hasText: '300750' })
  const group = asset.getByRole('combobox', { name: '组合分组' })
  const tags = asset.getByRole('textbox', { name: '自定义标签' })
  const style = asset.getByRole('combobox', { name: '投资风格' })
  const oldGroup = await group.inputValue()
  const oldTags = await tags.inputValue()
  const oldStyle = await style.inputValue()
  const oldSecondGroup = await second.getByRole('combobox', { name: '组合分组' }).inputValue()
  await group.fill('A股宽基')
  await tags.fill('核心,长期')
  await style.selectOption('BROAD_INDEX')
  await second.getByRole('combobox', { name: '组合分组' }).fill('A股卫星')
  await expect(asset).toContainText('未保存：投资风格、组合分组、自定义标签')
  await expect(second).toContainText('未保存：组合分组')
  await manager.getByRole('searchbox', { name: '搜索待分类资产' }).fill('600519')
  await expect(second).toBeHidden()
  const save = manager.getByRole('button', { name: '保存全部修改（2）' })
  await save.scrollIntoViewIfNeeded()
  const scrollBefore = await page.evaluate(() => window.scrollY)
  await save.click()
  await expect(manager.getByRole('status')).toContainText('已保存 2 项资产')
  await expect(asset).toContainText('已保存：投资风格、组合分组、自定义标签')
  expect(Math.abs(await page.evaluate(() => window.scrollY) - scrollBefore)).toBeLessThan(40)
  await manager.getByRole('searchbox', { name: '搜索待分类资产' }).fill('')
  await expect(second).toContainText('已保存：组合分组')

  await page.goto('/allocation?view=strategy')
  await expect(page.getByRole('heading', { level: 1, name: '自定义组合配置' })).toBeVisible()
  await expect(page.getByText('A股宽基', { exact: true }).first()).toBeVisible()
  await page.getByRole('textbox', { name: '新组合分组名称' }).fill('A股卫星')
  await page.getByRole('button', { name: '新增分组' }).click()
  await expect(page.getByRole('spinbutton', { name: 'A股卫星目标权重' })).toBeVisible()
  await page.getByRole('button', { name: '保存组合目标' }).click()
  await expect(page.getByTestId('write-flash')).toContainText('自定义组合目标已保存')

  await page.goto('/review/groups?scope=strategy%3AA%E8%82%A1%E5%AE%BD%E5%9F%BA')
  await expect(page.getByRole('heading', { level: 1, name: '分类投资复盘' })).toBeVisible()
  await expect(page.getByRole('navigation', { name: '分类维度' }).getByRole('link', { name: /组合分组/ })).toHaveAttribute('aria-current', 'page')
  await expect(page.getByRole('group', { name: '选择具体分组' }).getByRole('link', { name: 'A股宽基' })).toHaveAttribute('aria-current', 'page')
  await expect(page.getByRole('heading', { name: '组合 · A股宽基' })).toBeVisible()
  await expect(page.getByRole('link', { name: /贵州茅台/ })).toBeVisible()
  await page.getByRole('navigation', { name: '分类维度' }).getByRole('link', { name: /资产大类/ }).click()
  await expect(page.getByRole('navigation', { name: '分类维度' }).getByRole('link', { name: /资产大类/ })).toHaveAttribute('aria-current', 'page')
  await page.getByRole('group', { name: '分类复盘周期' }).getByRole('link', { name: '今年' }).click()
  await expect(page).toHaveURL(/period=THIS_YEAR/)
  await expect(page.getByRole('region', { name: '分类复盘结果' })).toContainText('期初资产')
  await page.goto('/review/returns?scope=strategy%3AA%E8%82%A1%E5%AE%BD%E5%9F%BA')
  await expect(page.getByRole('heading', { name: '组合 · A股宽基 · 历史收益' })).toBeVisible()

  await page.goto('/allocation?view=strategy')
  await page.getByRole('button', { name: '清除组合目标' }).click()
  await expect(page.getByTestId('write-flash')).toContainText('自定义组合目标已清除')
  await page.goto('/positions?view=composition')
  const restoreManager = page.getByRole('region', { name: '资产分组管理' })
  const restore = restoreManager.locator('[data-asset-id]').filter({ hasText: '600519' })
  await restore.getByRole('combobox', { name: '组合分组' }).fill(oldGroup)
  await restore.getByRole('textbox', { name: '自定义标签' }).fill(oldTags)
  await restore.getByRole('combobox', { name: '投资风格' }).selectOption(oldStyle)
  await restoreManager.locator('[data-asset-id]').filter({ hasText: '300750' }).getByRole('combobox', { name: '组合分组' }).fill(oldSecondGroup)
  await restoreManager.getByRole('button', { name: '保存全部修改（2）' }).click()
  await expect(restoreManager.getByRole('status')).toContainText('已保存 2 项资产')
})

test('组合目标不足 100% 时说明差额并可指定分组补足后保存', async ({ page }) => {
  await page.goto('/allocation?view=strategy')
  const weights = page.getByRole('spinbutton', { name: /目标权重/ })
  const count = await weights.count()
  expect(count).toBeGreaterThan(0)
  const firstName = (await weights.first().getAttribute('aria-label'))!.replace('目标权重', '')
  for (let index = 0; index < count; index += 1) await weights.nth(index).fill('0')
  await weights.first().fill('68.6')

  await expect(page.getByRole('status').getByText(/还差 31\.4%/)).toBeVisible()
  for (const width of [560, 800, 1280]) {
    await page.setViewportSize({ width, height: 900 })
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)
    expect(overflow, `${width}px 下目标差额操作区溢出`).toBeLessThanOrEqual(1)
  }
  await page.getByRole('button', { name: '保存组合目标' }).click()
  await expect(page.locator('.allocation-editor-footer').getByRole('alert')).toContainText('还差 31.4%')
  await page.getByRole('combobox', { name: '差额调整分组' }).selectOption({ label: firstName })
  await page.getByRole('button', { name: '补足所选分组' }).click()
  await expect(page.locator('.allocation-editor-footer')).toContainText('100.0%')
  await page.getByRole('button', { name: '保存组合目标' }).click()
  await expect(page.getByTestId('write-flash')).toContainText('自定义组合目标已保存')
  await page.reload()
  await expect(page.getByRole('button', { name: '清除组合目标' })).toBeVisible()
  await expect(page.locator('.allocation-editor-footer')).toContainText('100.0%')
  await page.getByRole('button', { name: '清除组合目标' }).click()
  await expect(page.getByTestId('write-flash')).toContainText('自定义组合目标已清除')
})
