import { test, expect } from '@playwright/test'

test('持仓宽表：提示剩余列，按钮与键盘滚动时固定资产列', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('/positions')
  const region = page.getByRole('region', { name: '持仓明细表' })
  const left = page.getByRole('button', { name: '向左查看列' })
  const right = page.getByRole('button', { name: '向右查看列' })
  await expect(page.getByText('横向滚动查看更多列')).toBeVisible()
  await expect(left).toBeDisabled()
  await expect(right).toBeEnabled()
  const firstCell = region.locator('tbody tr').first().locator('td').first()
  const before = await firstCell.boundingBox()
  await right.click()
  await expect(right).toBeDisabled()
  await expect(left).toBeEnabled()
  expect((await firstCell.boundingBox())?.x).toBeCloseTo(before!.x, 0)
  await left.click()
  await expect(left).toBeDisabled()
  await region.focus()
  await page.keyboard.press('ArrowRight')
  await expect.poll(() => region.evaluate((element) => element.scrollLeft)).toBeGreaterThan(0)
  await page.setViewportSize({ width: 1920, height: 1000 })
  await expect(page.getByText('横向滚动查看更多列')).toBeHidden()
})

test('目标试算：真实持仓金额权重可预览，取消保存不改计划', async ({ page }) => {
  await page.goto('/goals')
  const scenario = page.getByRole('region', { name: '临时试算', exact: true })
  const monthly = scenario.getByRole('slider').first()
  const original = await monthly.inputValue()
  const result = scenario.locator('.goal-scenario-results')
  const previous = await result.textContent()
  await monthly.focus()
  await monthly.press('ArrowRight')
  await expect(scenario.getByRole('button', { name: '保存到主目标', exact: true })).toBeEnabled()
  await expect(result).not.toHaveText(previous ?? '')
  await expect(scenario.getByRole('alert')).toHaveCount(0)
  await scenario.getByRole('button', { name: '保存到主目标', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '保存到主目标？' })).toBeVisible()
  await page.getByRole('dialog', { name: '保存到主目标？' }).getByRole('button', { name: '取消', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('region', { name: '临时试算', exact: true }).getByRole('slider').first()).toHaveValue(original)
})

test('目标试算：请求失败不展示旧结果，重试后恢复', async ({ page }) => {
  await page.goto('/goals')
  const scenario = page.getByRole('region', { name: '临时试算', exact: true })
  await page.route('**/goals', (route) => route.request().method() === 'POST' ? route.abort('failed') : route.continue())
  await scenario.getByRole('slider').first().focus()
  await scenario.getByRole('slider').first().press('ArrowRight')
  await expect(scenario.getByRole('alert')).toContainText('请重新试算')
  await expect(scenario.locator('.goal-scenario-results strong')).toHaveText(['—', '—', '—'])
  await expect(scenario.getByRole('button', { name: '保存到主目标', exact: true })).toBeDisabled()
  await page.unroute('**/goals')
  await scenario.getByRole('button', { name: '重新试算', exact: true }).click()
  await expect(scenario.getByRole('button', { name: '保存到主目标', exact: true })).toBeEnabled()
  await expect(scenario.getByRole('alert')).toHaveCount(0)
  await expect(scenario.locator('.goal-scenario-results strong').first()).not.toHaveText('—')
})
